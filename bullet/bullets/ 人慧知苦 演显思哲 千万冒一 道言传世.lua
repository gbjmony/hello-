其一​
慧根在苦，哲思由显。​
千万中出，道言初传。​
本非神授，皆自人间。​
为破迷障，为解倒悬。​
其二​
强权侧目，窥此精义。​
或为帝王，或为教寺。​
攫为己用，塑作威仪。​
令民跪拜，莫敢稍异。​
其三​
斥彼异见，为孽为魑。​
禁其唇舌，锢其心脾。​
顺我者昌，逆我者夷。​
千年暗室，不见天日。​
其四​
民有常欲，食暖居安。​
强名欲孽，实锁心猿。​
朱门酒肉，路有饥寒。​
谁执公道，颠倒坤乾。​
其五​
古之先哲，皆历厄困。​
呕心沥血，发愤著言。​
非为媚世，向强叫阵。​
字字泣血，原为争命。​
其六​
一旦被取，意旨顿改。​
削其锋芒，涂以粉黛。​
驯化为奴，教民忍耐。​
驭民之械，牧民之宰。​
其七​
枷锁层层，累世相因。​
焚书坑儒，血迹犹新。​
白骨累累，堆砌帝阙。​
谁解此痛，谁继前尘。​
其八​
星火不灭，反抗继起。​
揭竿斩木，前仆后继。​
宁碎枷锁，不苟活矣。​
千锁虽固，终有破时
其一​
风过林梢，叶落无声。​
心随境转，意自澄明。​
取舍之间，得失相生。​
一念放下，万般轻松。​
其二​
月挂疏桐，影落阶前。​
静听虫鸣，往事如烟。​
荣枯有数，聚散由天。​
珍惜当下，便是圆满。​
其三​
雨打窗棂，思绪万千。​
是非恩怨，过眼成篇。​
心若无尘，何处染嫌。​
笑对沧桑，自在安然。​
其四​
晨钟暮鼓，岁月流转。​
浮名薄利，过眼云烟。​
守住本心，不畏变迁。​
安然自得，便是神仙。
