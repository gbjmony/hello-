引入强化学习：通过奖励机制来塑造 AI 的 “成本意识”，若 AI 能以较少的 4 字表述思维链正确回答问题，就给予奖励，反之则进行惩罚，以此引导模型减少冗余推理，自动调整思考深度，生成更简短有效的思维链。

